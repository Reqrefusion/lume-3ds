"""Publish a fixed application plus external content; never assemble a 3DSX."""
from pathlib import Path
import hashlib,json,os,shutil,uuid

def digest(path):
 with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def state_file(name):
 return name.startswith('save.lum') or name.startswith('settings.') or name=='runtime.log' or name.endswith('.flag')
def publish(app,content,output,expected,report):
 app,content,output=Path(app).resolve(),Path(content).resolve(),Path(output).resolve()
 if any(state_file(Path(name).name) and '/' not in name for name in expected):raise ValueError('Generated assets must not contain user state')
 app_bytes=app.read_bytes()
 if app_bytes[:4]!=b'3DSX' or int.from_bytes(app_bytes[40:44],'little')!=0:raise ValueError('The distributed app must not contain an embedded filesystem')
 output.mkdir(parents=True,exist_ok=True);sd=output/'3ds';sd.mkdir(exist_ok=True);target=sd/'lume';binary=sd/'lume.3dsx'
 for path in [target,binary]:
  if path.is_symlink():raise ValueError('Output must not be a symbolic link')
 stage=output/('.lume-setup-'+uuid.uuid4().hex);stage.mkdir();assets=stage/'lume';assets.mkdir();preserved=[]
 backup=None;installed=False;binary_backup=None;binary_changed=False
 try:
  for name,record in expected.items():
   relative=Path(name)
   if relative.is_absolute() or '..' in relative.parts or ':' in name or '\\' in name:raise ValueError('Invalid content path')
   source=content/relative
   if source.is_symlink() or not source.resolve().is_relative_to(content):raise ValueError('Content must stay inside the prepared data directory')
   dest=assets/relative;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,dest)
   if dest.stat().st_size!=record['bytes'] or digest(dest)!=record['sha256']:raise ValueError('Copied content differs: '+name)
  # SD game state is never generated by setup. Keep any local test state intact.
  if target.is_dir():
   for source in target.iterdir():
    if source.is_file() and not source.is_symlink() and state_file(source.name):shutil.copyfile(source,assets/source.name);preserved.append(source.name)
  manifest={'format':2,'storage':'SD:/3ds/lume','app_sha256':digest(app),'files':expected,'generated_user_state':False}
  (assets/'content-manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
  shutil.copyfile(app,stage/'lume.3dsx')
  if target.exists():
   backups=output/'.setup-backups';backups.mkdir(exist_ok=True);backup=backups/('lume-'+uuid.uuid4().hex);os.replace(target,backup)
  os.replace(assets,target);installed=True
  if not binary.exists() or digest(binary)!=digest(app):
   if binary.exists():
    backups=output/'.setup-backups';backups.mkdir(exist_ok=True);binary_backup=backups/('lume-'+uuid.uuid4().hex+'.3dsx');shutil.copyfile(binary,binary_backup)
   os.replace(stage/'lume.3dsx',binary);binary_changed=True
  report.update({'app_sha256':digest(binary),'app_copied_unchanged':True,'content_files':len(expected),'storage':'external_sd','preserved_state':preserved,'backed_up_previous_content':str(backup) if backup else None})
  (output/'setup-report.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
  (output/'README.txt').write_text('Copy the 3ds folder to the root of your SD card. The fixed app is 3ds/lume.3dsx; original game content and user state are in 3ds/lume/. Do not redistribute your locally converted game media. Existing console saves do not need to be replaced.\n',encoding='ascii')
 except BaseException:
  if installed and target.exists():os.replace(target,stage/'failed-content')
  if backup and backup.exists():os.replace(backup,target)
  if binary_changed:
   if binary_backup:shutil.copyfile(binary_backup,binary)
   elif binary.exists():binary.unlink()
  raise
 finally:
  if stage.exists() and not stage.is_symlink() and stage.parent==output and stage.name.startswith('.lume-setup-'):shutil.rmtree(stage)
 return binary